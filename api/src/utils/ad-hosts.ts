/** Lowercases a host name and removes the trailing root dot. */
export function normalizeBlockHost(host: string): string {
  return host.trim().toLowerCase().replace(/\.$/, "");
}

const HOST_NAME = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*$/;

/** Reads a comma, space or newline separated host list (an env value). */
export function parseHostList(value: string | undefined): string[] {
  if (!value) return [];
  return value
    .split(/[\s,]+/)
    .map(normalizeBlockHost)
    .filter((host) => HOST_NAME.test(host));
}

/** Returns the list entry a host name falls under, or undefined. */
export type HostMatcher = (hostname: string) => string | undefined;

/**
 * Suffix matcher on whole labels: `ads.example.com` matches the entries
 * `ads.example.com` and `example.com`, never `notexample.com`. A host in
 * `allow` (or below one) is never matched, whatever `block` says.
 */
export function createHostMatcher(
  block: Iterable<string>,
  allow: Iterable<string> = [],
): HostMatcher {
  const blocked = new Set<string>();
  for (const host of block) {
    const normalized = normalizeBlockHost(host);
    if (normalized) blocked.add(normalized);
  }
  const allowed = new Set<string>();
  for (const host of allow) {
    const normalized = normalizeBlockHost(host);
    if (normalized) allowed.add(normalized);
  }
  // The most specific entry wins, so the walk goes from the full name upwards.
  const entryOf = (set: Set<string>, hostname: string): string | undefined => {
    if (!set.size) return undefined;
    let candidate = hostname;
    for (;;) {
      if (set.has(candidate)) return candidate;
      const dot = candidate.indexOf(".");
      if (dot === -1) return undefined;
      candidate = candidate.slice(dot + 1);
    }
  };
  return (hostname: string) => {
    const host = normalizeBlockHost(hostname);
    if (!host || entryOf(allowed, host)) return undefined;
    return entryOf(blocked, host);
  };
}

/** The matcher `blockAds` uses: the built-in list plus the operator's additions. */
export function createAdMatcher(extraHosts?: string, allowHosts?: string): HostMatcher {
  return createHostMatcher([...AD_HOSTS, ...parseHostList(extraHosts)], parseHostList(allowHosts));
}
